import type { LearningTeachBack } from '@ansimtrack/shared-types'

export function simplifyLearnerCopy(text: string) {
  let output = text.trim()

  for (const [source, target] of exactCopyReplacements) {
    if (output === source) {
      output = target
      break
    }
  }

  for (const [pattern, replacement] of copyReplacements) {
    output = output.replace(pattern, replacement)
  }

  return output
    .replace(/찾기해야/gu, '찾아야')
    .replace(/찾기해야 해요/gu, '찾아야 해요')
    .replace(/가기해야/gu, '가야')
    .replace(/가기해야 해요/gu, '가야 해요')
    .replace(/보기하기/gu, '보기')
    .replace(/어디로 어디로/gu, '어디로')
    .replace(/말를/gu, '말을')
    .replace(/때을/gu, '때는')
    .replace(/방송를/gu, '방송을')
    .replace(/전기가 안 좋으면/gu, '전기가 고장 난 것 같으면')
    .replace(/전기가 안 좋아요/gu, '전기가 고장 난 것 같아요')
    .replace(/전기가 안 좋을 때/gu, '전기 고장')
    .replace(/해야 합니다\.?/gu, '해야 해요.')
    .replace(/할 수 있습니다\.?/gu, '할 수 있어요.')
    .replace(/수 있습니다\.?/gu, '수 있어요.')
    .replace(/입니다\.?/gu, '이에요.')
    .replace(/합니다\.?/gu, '해요.')
    .replace(/않습니다\.?/gu, '않아요.')
    .replace(/  +/gu, ' ')
    .trim()
}

export function simplifyLearnerReason(text: string) {
  const output = text.trim()

  for (const [source, target] of exactReasonReplacements) {
    if (output === source) {
      return target
    }
  }

  return simplifyLearnerCopy(output)
}

export function simplifyLearnerWarning(text: string) {
  const output = text.trim()

  for (const [source, target] of exactWarningReplacements) {
    if (output === source) {
      return target
    }
  }

  return simplifyLearnerCopy(output)
}

export function simplifyTeachBack(teachBack: LearningTeachBack) {
  return {
    ...teachBack,
    options: teachBack.options.map((option) => ({
      ...option,
      feedback: simplifyLearnerCopy(option.feedback),
      label: simplifyLearnerCopy(option.label),
    })),
    prompt: simplifyLearnerCopy(teachBack.prompt),
  }
}

